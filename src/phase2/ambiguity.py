"""Phase II Step 4: ambiguity stress test.

Question: what happens to Jev's decision and confidence when the input supports more than one
plausible interpretation, or omits the information needed to pick one?

The three conditions are DIFFERENT KINDS of input, not points on an ordinal severity scale:

    clear                the original message, unchanged.
    competing_intents    the original request plus a second, explicit, plausible request.
    underspecified       the specific request is removed; only a vague topic remains.

Results are therefore compared condition by condition (confidence, acceptable-set accuracy and decision
behavior reported separately). No monotonic "confidence falls as ambiguity rises" trend is computed or
claimed across them.

Frozen dataset (built deterministically from the Bitext main sample; never regenerated at
evaluation time). For each source example A (true intent `a`) we pick a real distractor intent `b`
from the SAME Bitext choice set that shares a hand-defined intent FAMILY with `a` (refund, order,
account, ...), and build three variants:

    clear              the original message, unchanged.          primary=a, acceptable={a}
    competing_intents  the original message + a short hedged     primary=a (defensible: it leads and is
                       side-question about `b`.                  fully specified), acceptable={a, b}
    underspecified     a vague topic-only message for the        primary=None (no single label is
                       family (the specific request removed).    defensible), acceptable=family ∩ choices

The canonical field is `ambiguity_type`. `ambiguity_level` (CLEAR / SLIGHTLY_AMBIGUOUS / HIGHLY_AMBIGUOUS)
is kept only as a legacy alias for older readers; it implies an ordinal scale that is NOT claimed and is
not used by the analysis.

Underspecified items deliberately have NO forced single ground truth. The templates below are
hand-authored and inspectable; nothing is generated by a model.

Interpretation rule (fixed before any live run):
    clear              strict accuracy is valid.
    competing_intents  report BOTH strict accuracy and acceptable-set accuracy.
    underspecified     there is no unique ground truth: strict accuracy is not meaningful (it is null) and
                       acceptable-set accuracy is DESCRIPTIVE ONLY. The primary metrics are mean/median
                       confidence, the prediction distribution, distinct predictions, modal-prediction share
                       and the comparison with the clear condition.

Metrics (by provider and ambiguity_type): strict accuracy (only where a primary label exists),
acceptable-set accuracy, mean/median confidence, decision behavior (decision-flip rate vs the same
source's clear variant, number of distinct predictions and the modal prediction's share), and top-1/top-2
margin ONLY if the full probability distribution was recorded.
"""

import json
from pathlib import Path
from typing import Any

import pandas as pd

