"""Phase II Step 4: ambiguity stress test.

Question: what happens to Jev's decision and confidence when the input genuinely supports more
than one plausible interpretation?

Frozen dataset (built deterministically from the Bitext main sample; never regenerated at
evaluation time). For each source example A (true intent `a`) we pick a real distractor intent `b`
from the SAME Bitext choice set that shares a hand-defined intent FAMILY with `a` (refund, order,
account, ...), and build three variants:

    CLEAR                the original message, unchanged.          primary=a, acceptable={a}
    SLIGHTLY_AMBIGUOUS   the original message + a short hedged     primary=a (defensible: it leads and is
                         side-question about `b`.                  fully specified), acceptable={a, b}
    HIGHLY_AMBIGUOUS     a vague topic-only message for the        primary=None (no single label is
                         family (the specific request removed).    defensible), acceptable=family ∩ choices

Highly ambiguous items deliberately have NO forced single ground truth. The templates below are
hand-authored and inspectable; nothing is generated by a model.

Metrics (by provider and ambiguity level): strict accuracy (only where a primary label exists),
acceptable-set accuracy, mean/median confidence, decision-flip rate vs the same source's CLEAR
variant, and top-1/top-2 margin ONLY if the full probability distribution was recorded.
"""

import json
from pathlib import Path
from typing import Any

import pandas as pd

from phase2.stress import (
    PHASE2_RESULTS_DIR,
    STRESS_DIR,
    ExperimentSpec,
    StressError,
    pair_results,
    paired_metrics,
    select_bitext_sources,
    stable_int,
    top_margin,
)

NAME = "ambiguity"
DATASET_DIR = STRESS_DIR / "ambiguity"
RESULTS_DIR = PHASE2_RESULTS_DIR / "ambiguity"
N_SOURCES = 100
LEVELS = ("CLEAR", "SLIGHTLY_AMBIGUOUS", "HIGHLY_AMBIGUOUS")

# Intents that genuinely overlap. family -> (member intents, vague topic-only message)
FAMILIES: dict[str, tuple[list[str], str]] = {
    "refund": (["get_refund", "track_refund", "check_refund_policy"], "I have a question about my refund."),
    "order": (["cancel_order", "change_order", "place_order", "track_order"], "I need help with my order."),
    "cancellation": (["cancel_order", "check_cancellation_fee"], "I have a question about cancelling."),
    "invoice": (["check_invoice", "get_invoice"], "I need help with my invoice."),
    "payment": (["check_payment_methods", "payment_issue"], "I have a question about payment."),
    "account": (
        ["create_account", "delete_account", "edit_account", "switch_account", "registration_problems", "recover_password"],
        "I need help with my account.",
    ),
    "shipping_address": (["change_shipping_address", "set_up_shipping_address"], "I need help with my shipping address."),
    "delivery": (["delivery_options", "delivery_period"], "I have a question about delivery."),
    "contact": (["contact_customer_service", "contact_human_agent"], "I want to get in touch with someone."),
}

# Hedged side-question appended for SLIGHTLY_AMBIGUOUS, one per Bitext intent.
SIDE_QUESTION: dict[str, str] = {
    "cancel_order": "Also, I might want to cancel the order.",
    "change_order": "Also, I may need to change something in the order.",
    "change_shipping_address": "Also, the shipping address might need to change.",
    "check_cancellation_fee": "Also, is there a fee if I cancel?",
    "check_invoice": "Also, can I check the invoice?",
    "check_payment_methods": "Also, which payment methods can I use?",
    "check_refund_policy": "Also, what is your refund policy?",
    "complaint": "Also, I have a complaint.",
    "contact_customer_service": "Also, how do I contact customer service?",
    "contact_human_agent": "Also, can I talk to a human agent?",
    "create_account": "Also, I may want to create an account.",
    "delete_account": "Also, I might want to delete my account.",
    "delivery_options": "Also, what delivery options are there?",
    "delivery_period": "Also, how long does delivery take?",
    "edit_account": "Also, I may need to edit my account.",
    "get_invoice": "Also, can you send me the invoice?",
    "get_refund": "Also, I would like a refund.",
    "newsletter_subscription": "Also, about the newsletter subscription.",
    "payment_issue": "Also, there is an issue with a payment.",
    "place_order": "Also, I want to place an order.",
    "recover_password": "Also, I forgot my password.",
    "registration_problems": "Also, I have trouble registering.",
    "review": "Also, I want to leave a review.",
    "set_up_shipping_address": "Also, I need to set up a shipping address.",
    "switch_account": "Also, I want to switch accounts.",
    "track_order": "Also, where is my order?",
    "track_refund": "Also, where is my refund?",
}


def validate_level(level: str) -> str:
    if level not in LEVELS:
        raise StressError(f"Unknown ambiguity_level {level!r}; expected one of {LEVELS}.")
    return level


def shared_families(a: str, b: str) -> list[str]:
    return sorted(f for f, (members, _) in FAMILIES.items() if a in members and b in members)


def pick_partner(source_id: str, truth: str, choices: list[str]) -> tuple[str, str] | None:
    """A distractor `b` in the same choice set that shares a family with the truth, chosen deterministically."""
    options = sorted((c, fam) for c in choices if c != truth for fam in shared_families(truth, c)[:1])
    if not options:
        return None
    return options[stable_int("ambiguity-partner", source_id) % len(options)]


def acceptable_set_correct(prediction: str | None, acceptable: list[str]) -> bool | None:
    """Whether the prediction is one of the defensible intents. None when there was no prediction."""
    if prediction is None:
        return None
    return prediction in acceptable


def build_variants(source_id: str, text: str, choices: list[str], truth: str, partner: str, family: str) -> list[dict[str, Any]]:
    members, vague = FAMILIES[family]
    high_acceptable = sorted(m for m in members if m in choices)
    common = {"source_example_id": source_id, "original_text": text, "original_ground_truth": truth, "candidates": choices, "secondary_intent": partner, "family": family}
    return [
        {
            **common,
            "variant_id": f"{source_id}:CLEAR",
            "ambiguity_level": "CLEAR",
            "text": text,
            "ground_truth": truth,
            "primary_expected_intent": truth,
            "acceptable_intents": [truth],
            "transformation": "none (original Bitext message)",
        },
        {
            **common,
            "variant_id": f"{source_id}:SLIGHTLY_AMBIGUOUS",
            "ambiguity_level": "SLIGHTLY_AMBIGUOUS",
            "text": f"{text.rstrip()} {SIDE_QUESTION[partner]}",
            "ground_truth": truth,
            "primary_expected_intent": truth,
            "acceptable_intents": sorted({truth, partner}),
            "transformation": f"original message + hedged side-question about '{partner}'",
        },
        {
            **common,
            "variant_id": f"{source_id}:HIGHLY_AMBIGUOUS",
            "ambiguity_level": "HIGHLY_AMBIGUOUS",
            "text": vague,
            "ground_truth": None,  # no single label is defensible
            "primary_expected_intent": None,
            "acceptable_intents": high_acceptable,
            "transformation": f"specific request removed; vague '{family}' topic message",
        },
    ]


def build() -> tuple[list[dict[str, Any]], dict[str, Any]]:
    pool = [r for r in select_bitext_sources(1000) if pick_partner(r.id, r.ground_truth, r.choices)]
    chosen = sorted(pool, key=lambda r: stable_int("ambiguity-source", r.id))[:N_SOURCES]
    rows: list[dict[str, Any]] = []
    for r in sorted(chosen, key=lambda r: r.id):
        partner, family = pick_partner(r.id, r.ground_truth, r.choices)  # type: ignore[misc]
        rows.extend(build_variants(r.id, r.text, r.choices, r.ground_truth, partner, family))
    meta = {
        "experiment": NAME,
        "source": "data/samples/bitext_main.jsonl (Bitext test split, frozen main sample)",
        "n_sources_requested": N_SOURCES,
        "levels": list(LEVELS),
        "families": {k: v[0] for k, v in FAMILIES.items()},
        "generation_method": "deterministic hand-authored templates (no model generation)",
        "review_status": "pending_human_review",
    }
    return rows, meta


def describe(rows: list[dict[str, Any]]) -> dict[str, Any]:
    df = pd.DataFrame(rows)
    pairs = df[df["ambiguity_level"] == "SLIGHTLY_AMBIGUOUS"].groupby(["original_ground_truth", "secondary_intent"]).size()
    examples = []
    for level in LEVELS:
        for r in [r for r in rows if r["ambiguity_level"] == level][:: max(1, N_SOURCES // 4)][:4]:
            examples.append({k: r[k] for k in ("variant_id", "ambiguity_level", "text", "primary_expected_intent", "acceptable_intents")})
    return {
        "n_source_examples": df["source_example_id"].nunique(),
        "n_variants": len(df),
        "counts_by_ambiguity_level": df["ambiguity_level"].value_counts().to_dict(),
        "families_used": df[df["ambiguity_level"] == "CLEAR"]["family"].value_counts().to_dict(),
        "intent_pairs (truth -> secondary)": {f"{a} -> {b}": int(n) for (a, b), n in pairs.items()},
        "representative_examples": examples[:12],
    }


def _acceptable(cell: Any) -> list[str]:
    return json.loads(cell) if isinstance(cell, str) else list(cell)


def enrich(results: pd.DataFrame) -> pd.DataFrame:
    """Add acceptable-set correctness, strict correctness (only where a primary label exists) and margin."""
    df = results.copy()
    for level in df["ambiguity_level"].unique():
        validate_level(level)
    df["acceptable_correct"] = [acceptable_set_correct(p, _acceptable(a)) if pd.notna(p) else None for p, a in zip(df["prediction"], df["acceptable_intents"], strict=True)]
    has_primary = df["primary_expected_intent"].notna()
    df["strict_correct"] = [(p == e) if (h and pd.notna(p)) else None for p, e, h in zip(df["prediction"], df["primary_expected_intent"], has_primary, strict=True)]
    df["margin"] = [top_margin(json.loads(s)) if isinstance(s, str) else None for s in df["probabilities_json"]]
    return df


def analyze(results: pd.DataFrame) -> tuple[dict[str, pd.DataFrame], dict[str, Any]]:
    df = enrich(results)
    clear = df[df["ambiguity_level"] == "CLEAR"]
    rows, pair_rows = [], []
    for (provider, level), grp in df.groupby(["provider", "ambiguity_level"], sort=True):
        ok = grp[grp["prediction"].notna()]
        strict = ok[ok["strict_correct"].notna()]
        margins = ok["margin"].dropna()
        row = {
            "provider": provider,
            "ambiguity_level": level,
            "n": len(grp),
            "n_predicted": len(ok),
            "n_strict_scorable": len(strict),
            "strict_accuracy": float(strict["strict_correct"].astype(bool).mean()) if len(strict) else None,
            "acceptable_set_accuracy": float(ok["acceptable_correct"].astype(bool).mean()) if len(ok) else None,
            "mean_confidence": float(ok["confidence"].mean()) if len(ok) else None,
            "median_confidence": float(ok["confidence"].median()) if len(ok) else None,
            "mean_top1_top2_margin": float(margins.mean()) if len(margins) else None,
            "n_with_margin": len(margins),
            "margin_note": "available" if len(margins) else "unavailable: full probabilities not recorded",
        }
        if level != "CLEAR":
            paired = pair_results(clear[clear["provider"] == provider], grp)
            m = paired_metrics(paired)
            row.update({"n_pairs_vs_clear": m["n_pairs"], "decision_flip_rate_vs_clear": m.get("decision_flip_rate"), "mean_confidence_delta_vs_clear": m.get("mean_confidence_delta")})
            for _, p in paired.iterrows():
                pair_rows.append(
                    {
                        "provider": provider,
                        "source_example_id": p["source_example_id"],
                        "ambiguity_level": level,
                        "original_prediction": p["prediction_base"],
                        "ambiguous_prediction": p["prediction_variant"],
                        "original_confidence": p["confidence_base"],
                        "ambiguous_confidence": p["confidence_variant"],
                        "prediction_changed": (p["prediction_base"] != p["prediction_variant"]) if pd.notna(p["prediction_variant"]) and pd.notna(p["prediction_base"]) else None,
                    }
                )
        rows.append(row)
    by_level = pd.DataFrame(rows)
    summary = {
        "experiment": NAME,
        "n_results": len(df),
        "providers": sorted(df["provider"].unique()),
        "definitions": {
            "strict_accuracy": "prediction == primary_expected_intent; only rows that have a primary label (null for HIGHLY_AMBIGUOUS)",
            "acceptable_set_accuracy": "prediction is any defensible intent in acceptable_intents",
            "decision_flip_rate_vs_clear": "share of pairs whose predicted label differs from the same source's CLEAR variant",
        },
        "interpretation": "not concluded here; compare mean_confidence across levels with the n shown",
    }
    return {"ambiguity_by_level": by_level, "ambiguity_pairs": pd.DataFrame(pair_rows)}, summary


SPEC = ExperimentSpec(name=NAME, dataset_dir=DATASET_DIR, results_dir=RESULTS_DIR, build=build, describe=describe, analyze=analyze)
