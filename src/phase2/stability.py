"""Phase II Step 5: semantic stability.

Question: does Jev make the same decision when the meaning stays the same but the wording changes?

Frozen dataset built deterministically from a fixed subset of the Bitext main sample. Each source
example gets an `original` control row plus two families of variants, kept strictly separate:

  A. surface_*     mechanical, meaning-preserving text changes (case, punctuation, one typo,
                   filler removal). Deterministic functions of the source text (typo position is
                   seeded by the source id).
  B. paraphrase_*  natural paraphrases from a hand-authored, INTENT-LEVEL bank (three per Bitext
                   intent), written once by the project author and frozen for human review. They
                   restate the intent, not the source's particular wording or details, so they test
                   whether the decision survives a change of phrasing. Nothing is generated by a
                   model at build or evaluation time. Noise-style corruption belongs to Step 6.

Every comparison is PAIRED: each variant is compared with its own source's original row.
"""

