_FILLERS = re.compile(r"\b(please|could you|can you|would you|i would like to|i'd like to|i want to|i need to|i have to|hello|hi|thanks|thank you)\b[,.!]?", re.IGNORECASE)


def normalize(text: str) -> str:
    """Whitespace-only normalization. Case is deliberately preserved: changing case IS a variant."""
    return re.sub(r"\s+", " ", text.strip())


def surface_uppercase(text: str, source_id: str) -> str:
    return text.upper()


def surface_lowercase_nopunct(text: str, source_id: str) -> str:
    return re.sub(r"\s+", " ", text.lower().translate(str.maketrans("", "", string.punctuation.replace("{", "").replace("}", "")))).strip()


def surface_exclaim(text: str, source_id: str) -> str:
    return text.rstrip(" .!?") + "!!!"


def surface_typo(text: str, source_id: str) -> str:
    """Drop one interior character from the longest alphabetic word (>=5 letters); position seeded by source id."""
    words = list(re.finditer(r"[A-Za-z]{5,}", text))
    if not words:
        return text
    word = max(words, key=lambda m: (len(m.group()), -m.start()))
    idx = word.start() + 1 + stable_int("stability-typo", source_id) % (len(word.group()) - 2)
    return text[:idx] + text[idx + 1 :]


def surface_compress(text: str, source_id: str) -> str:
    out = re.sub(r"\s+", " ", _FILLERS.sub(" ", text)).strip(" ,")
    return out or text


SURFACE_FUNCS = {
    "surface_uppercase": surface_uppercase,
    "surface_lowercase_nopunct": surface_lowercase_nopunct,
    "surface_exclaim": surface_exclaim,
    "surface_typo": surface_typo,
    "surface_compress": surface_compress,
}


def detect_duplicate_variants(original: str, variants: dict[str, str]) -> dict[str, str]:
    """variant_type -> reason, for variants whose text (ignoring extra whitespace) repeats the original or an earlier variant."""
    seen = {normalize(original): "original"}
    dupes: dict[str, str] = {}
    for vtype, text in variants.items():
        key = normalize(text)
        if key in seen:
            dupes[vtype] = f"duplicate of {seen[key]}"
        else:
            seen[key] = vtype
    return dupes


def variants_for_source(source_id: str, text: str, choices: list[str], truth: str) -> tuple[list[dict[str, Any]], dict[str, str]]:
    """The original row plus every non-duplicate variant. Returns (rows, dropped {variant_type: reason})."""
    proposed = {t: f(text, source_id) for t, f in SURFACE_FUNCS.items()}
    proposed.update({f"paraphrase_{i + 1}": p for i, p in enumerate(PARAPHRASES[truth])})
    dropped = detect_duplicate_variants(text, proposed)
    base = {"source_example_id": source_id, "original_text": text, "expected_label": truth, "ground_truth": truth, "candidates": choices, "intent": truth}
    rows = [{**base, "variant_id": f"{source_id}:original", "variant_type": "original", "variant_family": "original", "text": text}]
    for vtype, vtext in proposed.items():
        if vtype in dropped:
            continue
        rows.append({**base, "variant_id": f"{source_id}:{vtype}", "variant_type": vtype, "variant_family": vtype.split("_")[0], "text": vtext})
    return rows, dropped


def build() -> tuple[list[dict[str, Any]], dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    dropped_total: dict[str, int] = {}
    for r in sorted(select_bitext_sources(N_SOURCES), key=lambda r: r.id):
        src_rows, dropped = variants_for_source(r.id, r.text, r.choices, r.ground_truth)
        rows.extend(src_rows)
        for vtype in dropped:
            dropped_total[vtype] = dropped_total.get(vtype, 0) + 1
    meta = {
        "experiment": NAME,
        "source": "data/samples/bitext_main.jsonl via phase2.stress.select_bitext_sources",
        "n_sources_requested": N_SOURCES,
        "variant_families": {"surface": list(SURFACE_TYPES), "paraphrase": ["paraphrase_1", "paraphrase_2", "paraphrase_3"]},
        "generation_method": "surface: deterministic functions; paraphrase: hand-authored intent-level bank written once by the project author (no model generation)",
        "paraphrase_caveat": "paraphrases restate the intent, not each source message's specific details",
        "duplicate_variants_dropped": dropped_total,
        "review_status": "pending_human_review",
    }
    return rows, meta


def describe(rows: list[dict[str, Any]]) -> dict[str, Any]:
    df = pd.DataFrame(rows)
    fam = []
    for src in list(dict.fromkeys(df["source_example_id"]))[:10]:
        g = df[df["source_example_id"] == src]
        fam.append({"source_example_id": src, "expected_label": g["expected_label"].iloc[0], "variants": dict(zip(g["variant_type"], g["text"], strict=True))})
    return {
        "n_source_examples": df["source_example_id"].nunique(),
        "n_rows_including_originals": len(df),
        "counts_by_variant_type": df["variant_type"].value_counts().to_dict(),
        "counts_by_family": df["variant_family"].value_counts().to_dict(),
        "example_families": fam,
    }


def confidence_variance_within_families(results: pd.DataFrame) -> pd.DataFrame:
    """Per provider and source: variance of confidence across the original + its variants."""
    ok = results[results["confidence"].notna()]
    rows = []
    for (provider, src), grp in ok.groupby(["provider", "source_example_id"]):
        rows.append({"provider": provider, "source_example_id": src, "n_rows": len(grp), "confidence_variance": float(grp["confidence"].var(ddof=0)), "n_distinct_predictions": int(grp["prediction"].nunique())})
    return pd.DataFrame(rows)


def analyze(results: pd.DataFrame) -> tuple[dict[str, pd.DataFrame], dict[str, Any]]:
    if not (results["variant_type"] == "original").any():
        raise StressError("No 'original' rows in the results; paired comparison needs each source's original.")
    base = results[results["variant_type"] == "original"]
    variants = results[results["variant_type"] != "original"]
    paired = pair_results(base, variants)
    by_type = grouped_paired_metrics(paired, ["provider", "variant_family", "variant_type"])
    by_family = grouped_paired_metrics(paired, ["provider", "variant_family"])
    by_intent = grouped_paired_metrics(paired.assign(dataset="bitext"), ["provider", "dataset", "intent"])
    overall = grouped_paired_metrics(paired, ["provider"])
    variance = confidence_variance_within_families(results)
    pairs = paired[["provider", "source_example_id", "variant_type", "variant_family", "expected_label", "prediction_base", "prediction_variant", "confidence_base", "confidence_variant", "correct_base", "correct_variant"]].copy()
    pairs["prediction_agrees"] = pairs["prediction_base"] == pairs["prediction_variant"]
    pairs["confidence_delta"] = pairs["confidence_variant"] - pairs["confidence_base"]
    summary = {
        "experiment": NAME,
        "n_results": len(results),
        "pairing": "every variant is compared with its own source's original row (same provider)",
        "overall": overall.to_dict("records"),
        "mean_within_source_confidence_variance": variance.groupby("provider")["confidence_variance"].mean().to_dict(),
        "interpretation": "not concluded here; read rates together with n_pairs",
    }
    tables = {"stability_by_variant_type": by_type, "stability_by_family": by_family, "stability_by_intent": by_intent, "stability_pairs": pairs, "confidence_variance": variance}
    return tables, summary


SPEC = ExperimentSpec(name=NAME, dataset_dir=DATASET_DIR, results_dir=RESULTS_DIR, build=build, describe=describe, analyze=analyze)
